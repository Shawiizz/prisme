"""Writes src/gpu/matmul_blocked.wgsl: the linear layers on the shader cores, each thread
computing a block of ROWS x COLS outputs from registers alone, without workgroup memory.

    python matmul_blocked.py > ../src/gpu/matmul_blocked.wgsl

The loops are written out: a compiler keeps named values in registers where it may spill an
array. The shape was chosen on an Adreno 740 (`examples/matmul_bench.rs`): 8 x 8 blocks in
workgroups of 8 x 8 threads ran the products of a chunk at 330 to 380 GFLOP/s there, against
78 for the tiles in workgroup memory, and 7 times faster on an NVIDIA card too; larger blocks
spill.
"""

ROWS, COLS, WX, WY = 8, 8, 8, 8
# the gated layers take a thread's columns as 4 gates and their 4 values
assert COLS == 8

HEADER = f"""// Generated by tools/matmul_blocked.py: edit that, not this.
//
// c[r, j] (+)= act(sum_k a[r, k] * w[j, k] + bias[j]): a linear layer over `m` rows, each
// thread computing {ROWS} x {COLS} outputs from registers alone (a mobile GPU's workgroup memory
// is slow), reading A and the f16 weights four values of k at a time. `k`, `lda` and `a_off`
// are multiples of 4 (the plan falls back on matmul_small.wgsl otherwise). Rows and columns
// past the ends read the last ones, and are not written.
//
// For a gated feed-forward (act 3, or 4 for SiLU) the columns come in groups of 4 gates then
// their 4 values, and the layer writes act(gate) * value, n / 2 columns.
//
// bench: rows={ROWS * WY} cols={COLS * WX}

struct Params {{
    m: u32,
    n: u32,
    k: u32,
    lda: u32,
    a_off: u32,
    ldc: u32,
    c_off: u32,
    // 0: none, 1: GELU, 2: tanh, 3: gated GELU, 4: gated SiLU
    act: u32,
    accumulate: u32,
    has_bias: u32,
}}

@group(0) @binding(0) var<storage, read> a: array<vec4<f32>>;
// f16 weights, four to a pair of words
@group(0) @binding(1) var<storage, read> w: array<vec2<u32>>;
@group(0) @binding(2) var<storage, read> bias: array<f32>;
@group(0) @binding(3) var<storage, read_write> c: array<f32>;
@group(0) @binding(4) var<uniform> p: Params;

fn erf(x: f32) -> f32 {{
    // Abramowitz & Stegun 7.1.26, |error| < 1.5e-7
    let t = 1.0 / (1.0 + 0.3275911 * abs(x));
    let y = 1.0 - ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) * t + 0.254829592) * t * exp(-x * x);
    return select(-y, y, x >= 0.0);
}}

fn gelu(x: f32) -> f32 {{
    return 0.5 * x * (1.0 + erf(x * 0.70710678118654752));
}}

fn activate(x: f32) -> f32 {{
    switch p.act {{
        case 1u: {{ return gelu(x); }}
        case 2u: {{ return tanh(clamp(x, -15.0, 15.0)); }}
        default: {{ return x; }}
    }}
}}

fn store(r: u32, col: u32, x: f32) {{
    if (r >= p.m || col >= p.n) {{
        return;
    }}
    var v = x;
    if (p.has_bias != 0u) {{
        v += bias[col];
    }}
    v = activate(v);
    let at = p.c_off + r * p.ldc + col;
    if (p.accumulate != 0u) {{
        v += c[at];
    }}
    c[at] = v;
}}

// the gate of column `col` and its value 4 columns on, into column col / 8 * 4 + col % 8
fn store_gated(r: u32, col: u32, gate: f32, value: f32) {{
    if (r >= p.m || col >= p.n) {{
        return;
    }}
    var g = gate;
    var v = value;
    if (p.has_bias != 0u) {{
        g += bias[col];
        v += bias[col + 4u];
    }}
    var gated = 0.0;
    if (p.act == 4u) {{
        gated = g / (1.0 + exp(-g)) * v;
    }} else {{
        gated = gelu(g) * v;
    }}
    c[p.c_off + r * p.ldc + col / 8u * 4u + col % 8u] = gated;
}}
"""


def kernel():
    groups = COLS // 4
    lines = [HEADER, f"@compute @workgroup_size({WX}, {WY})", "fn main(@builtin(global_invocation_id) g: vec3<u32>) {"]
    lines += [
        f"    let row0 = g.y * {ROWS}u;",
        f"    let col0 = g.x * {COLS}u;",
        "    let last_row = p.m - 1u;",
        "    let last_col = p.n - 1u;",
        "    let kq = p.k / 4u;",
    ]
    lines += [f"    let ar{i} = (p.a_off + min(row0 + {i}u, last_row) * p.lda) / 4u;" for i in range(ROWS)]
    lines += [f"    let wr{j} = min(col0 + {j}u, last_col) * kq;" for j in range(COLS)]
    lines += [f"    var acc{i}_{g} = vec4<f32>(0.0);" for i in range(ROWS) for g in range(groups)]
    lines.append("    for (var q = 0u; q < kq; q++) {")
    for j in range(COLS):
        lines.append(f"        let p{j} = w[wr{j} + q];")
        lines.append(f"        let w{j} = vec4(unpack2x16float(p{j}.x), unpack2x16float(p{j}.y));")
    # the weights turned around: t{g}_{kk} holds columns 4g to 4g + 3 at k = kk
    for g in range(groups):
        for kk, comp in enumerate("xyzw"):
            lines.append(f"        let t{g}_{kk} = vec4({', '.join(f'w{4 * g + jj}.{comp}' for jj in range(4))});")
    for i in range(ROWS):
        lines.append(f"        let a{i} = a[ar{i} + q];")
        for g in range(groups):
            for kk, comp in enumerate("xyzw"):
                lines.append(f"        acc{i}_{g} = fma(vec4(a{i}.{comp}), t{g}_{kk}, acc{i}_{g});")
    lines.append("    }")
    lines.append("    if (p.act >= 3u) {")
    for i in range(ROWS):
        for jj, comp in enumerate("xyzw"):
            lines.append(f"        store_gated(row0 + {i}u, col0 + {jj}u, acc{i}_0.{comp}, acc{i}_1.{comp});")
    lines += ["        return;", "    }"]
    for i in range(ROWS):
        for g in range(groups):
            for jj, comp in enumerate("xyzw"):
                lines.append(f"    store(row0 + {i}u, col0 + {4 * g + jj}u, acc{i}_{g}.{comp});")
    lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    import sys

    sys.stdout.reconfigure(newline="\n")
    print(kernel(), end="")
